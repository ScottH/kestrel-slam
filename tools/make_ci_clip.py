"""Cuts a short, self-contained clip out of an ASL-format dataset (EuRoC / TUM-VI layout) for the
quick CI regression test, and packs it with the place-recognition vocabulary into one archive.

    # inside the dev container:
    tools/make_ci_clip.py /data/datasets/tumvi/room1_512_16 --duration 40 \\
        --name tumvi_room1_40s --vocabulary /data/vocabulary/kestrel_orb_k10L5.fbow \\
        --out /data/ci

produces
    /data/ci/kestrel_ci_data.tar.gz          datasets/<name>/mav0/... + vocabulary/<file>
    /data/ci/kestrel_ci_data.tar.gz.sha256

The archive is published as a GitHub release asset; CI downloads it, checks the SHA-256 pinned
in .github/workflows/ci.yml and unpacks it into its data folder (docs/benchmarks.md).

What is kept:
  * camera frames whose timestamp lies in [start, start + duration), both cameras. 16-bit images
    are converted to 8-bit with the SAME OpenCV call the pipeline uses to read them
    (cv::imread(..., IMREAD_GRAYSCALE)), so the clip is bit-identical to what Kestrel sees on the
    full sequence, and half the size;
  * IMU and ground truth over the same interval plus a 1 s margin on each side (the estimator
    integrates IMU between frames; the evaluation interpolates ground truth);
  * every other file of the sequence (calibration yaml etc.), and a README with attribution.

The archive is reproducible: fixed file order, zeroed timestamps and owners in the tar, and gzip
without a name or time stamp, so the same input always gives the same SHA-256.
"""

import argparse
import csv
import gzip
import hashlib
import io
import pathlib
import shutil
import sys
import tarfile

import cv2

MARGIN_NS = 1_000_000_000

README = """# Kestrel CI clip: {name}

Excerpt of `{source}`: {frames} stereo frames, t = {start:.1f} s ... {end:.1f} s of the sequence,
images converted to 8-bit (as Kestrel reads them). Generated by `tools/make_ci_clip.py`.

Source dataset: **The TUM VI Benchmark for Evaluating Visual-Inertial Odometry**, D. Schubert,
T. Goll, N. Demmel, V. Usenko, J. Stueckler, D. Cremers, IROS 2018.
https://cvg.cit.tum.de/data/datasets/visual-inertial-dataset — licensed under CC BY 4.0
(https://creativecommons.org/licenses/by/4.0/). Changes: temporal excerpt, 16 → 8 bit images.
"""


def read_rows(path):
    with open(path, newline='') as f:
        lines = f.read().splitlines()
    header = [l for l in lines if l.startswith('#')]
    rows = [l for l in lines if l and not l.startswith('#')]
    return header, rows


def stamp(row):
    return int(row.split(',', 1)[0])


def copy_csv(src, dst, lo, hi):
    header, rows = read_rows(src)
    kept = [r for r in rows if lo <= stamp(r) < hi]
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text('\n'.join(header + kept) + '\n')
    return kept


def cut(source: pathlib.Path, dest: pathlib.Path, start_s: float, duration_s: float) -> dict:
    mav = source / 'mav0'
    _, cam_rows = read_rows(mav / 'cam0' / 'data.csv')
    t0 = stamp(cam_rows[0])
    lo, hi = t0 + int(start_s * 1e9), t0 + int((start_s + duration_s) * 1e9)

    out = dest / 'mav0'
    frames = 0
    for sensor in sorted(p for p in mav.iterdir() if p.is_dir()):
        target = out / sensor.name
        target.mkdir(parents=True, exist_ok=True)
        for extra in sorted(p for p in sensor.iterdir() if p.is_file() and p.name != 'data.csv'):
            shutil.copy2(extra, target / extra.name)
        if not (sensor / 'data.csv').exists():
            continue
        if sensor.name.startswith('cam'):
            kept = copy_csv(sensor / 'data.csv', target / 'data.csv', lo, hi)
            (target / 'data').mkdir(exist_ok=True)
            for row in kept:
                name = row.split(',')[1].strip()
                img = cv2.imread(str(sensor / 'data' / name), cv2.IMREAD_GRAYSCALE)
                if img is None:
                    sys.exit(f'cannot read {sensor / "data" / name}')
                cv2.imwrite(str(target / 'data' / name), img, [cv2.IMWRITE_PNG_COMPRESSION, 9])
            frames = max(frames, len(kept))
        else:
            copy_csv(sensor / 'data.csv', target / 'data.csv', lo - MARGIN_NS, hi + MARGIN_NS)
    return {'frames': frames, 'start': start_s, 'end': start_s + duration_s}


def pack(root: pathlib.Path, archive: pathlib.Path):
    """Deterministic tar.gz of everything under root (sorted, no times/owners)."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode='w', format=tarfile.PAX_FORMAT) as tar:
        for path in sorted(root.rglob('*')):
            info = tar.gettarinfo(str(path), arcname=str(path.relative_to(root)))
            info.mtime, info.uid, info.gid, info.uname, info.gname = 0, 0, 0, '', ''
            info.mode = 0o755 if path.is_dir() else 0o644
            if path.is_file():
                with open(path, 'rb') as f:
                    tar.addfile(info, f)
            else:
                tar.addfile(info)
    with open(archive, 'wb') as raw:
        with gzip.GzipFile(filename='', mode='wb', fileobj=raw, mtime=0, compresslevel=6) as gz:
            gz.write(buf.getvalue())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    pathlib.Path(str(archive) + '.sha256').write_text(f'{digest}  {archive.name}\n')
    return digest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('source', type=pathlib.Path, help='sequence folder containing mav0/')
    parser.add_argument('--name', required=True, help='clip name (folder under datasets/ci/)')
    parser.add_argument('--start', type=float, default=0.0, help='start [s after first frame]')
    parser.add_argument('--duration', type=float, default=40.0, help='length [s]')
    parser.add_argument('--vocabulary', type=pathlib.Path, required=True)
    parser.add_argument('--out', type=pathlib.Path, default=pathlib.Path('/data/ci'))
    args = parser.parse_args()

    staging = args.out / 'staging'
    if staging.exists():
        shutil.rmtree(staging)
    clip = staging / 'datasets' / 'ci' / args.name
    info = cut(args.source, clip, args.start, args.duration)
    (clip / 'README.md').write_text(README.format(name=args.name, source=args.source.name, **info))
    (staging / 'vocabulary').mkdir(parents=True)
    shutil.copy2(args.vocabulary, staging / 'vocabulary' / args.vocabulary.name)

    archive = args.out / 'kestrel_ci_data.tar.gz'
    digest = pack(staging, archive)
    print(f"{info['frames']} frames, {archive.stat().st_size / 1e6:.1f} MB, sha256 {digest}")
    print(f'unpacked copy for local runs: {staging}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
